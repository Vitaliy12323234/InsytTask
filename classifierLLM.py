import pandas as pd
import json
import requests
import sys

MODEL_NAME = "qwen3.5:9b"
URL = "http://127.0.0.1:11434/api/chat"

SYSTEM_PROMPT = """Ты — эксперт техподдержки корпоративной образовательной платформы (LMS).
Классифицируй обращение пользователя.

### ШАГ 1. Ручная обработка.
Если выполнено ХОТЯ БЫ ОДНО условие — верни category="Не определено", tag="Требует ручной обработки", requires_manual_review=true:
  1) строка пустая или только пробелы;
  2) длина текста (без крайних пробелов) меньше 5 символов;
  3) нет ни одной буквы русского алфавита (А-Я, а-я, Ё, ё);
  4) только эмоция без описания проблемы (например: «Кошмар!!!», «Спасибо!», «Ура!»).

### ШАГ 2. Иначе выбери ОДНУ из 5 категорий:
  1. "Авторизация" — вход, пароль, восстановление доступа, активация учётной записи.
  2. "Ошибка загрузки" — сбои открытия, передачи и воспроизведения страниц, файлов, видео.
  3. "Организационные вопросы по обучению" — назначение/отмена курсов, зачисление в потоки, расписание, сроки, запрос доступа к курсу.
  4. "Ошибки в контенте/методологии" — опечатки, неверные формулы, противоречия материалов, ошибки в условиях заданий.
  5. "Не завершается обучение" — не сохраняется прогресс, не засчитываются результаты, не выдаётся документ при выполненных условиях.

### ПРИОРИТЕТ:
  - вход/пароль → "Авторизация"
  - видео/файл/страница/404/500 → "Ошибка загрузки"
  - назначить/отменить/продлить/удалить/открыть доступ → "Организационные вопросы по обучению"
  - сертификат/прогресс/статус → "Не завершается обучение"
  - неверный ответ/опечатка → "Ошибки в контенте/методологии"

### ТЕГИ:
  "Авторизация", "Ошибка загрузки" → "Технический"
  "Организационные вопросы по обучению", "Ошибки в контенте/методологии", "Не завершается обучение" → "Организационный"

### ОТВЕТ — строго JSON:
{"category": "...", "tag": "...", "requires_manual_review": true|false}
"""

def classify(text):
    if pd.isna(text):
        text = ""
    payload = {
        "model": MODEL_NAME,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": f'Обращение: "{text}"'}
        ],
        "stream": False,
        "format": "json",
        "think": False,
        "options": {"temperature": 0.0}
    }
    r = requests.post(URL, json=payload, timeout=180)
    return json.loads(r.json()["message"]["content"])

def main():
    df = pd.read_csv("tikets.csv", encoding="utf-8-sig")
    total = len(df)
    rows = []

    for i, row in df.iterrows():
        # Крутилка
        sys.stdout.write(f"\r[{i+1}/{total}] обработка...")
        sys.stdout.flush()

        res = classify(row["text"])
        rows.append({
            "id": row["id"],
            "text": row["text"],
            "category": res["category"],
            "tag": res["tag"],
            "requires_manual_review": str(res["requires_manual_review"]).lower(),
            "status": "ok",
            "error": ""
        })

    pd.DataFrame(rows).to_csv("result.csv", index=False, encoding="utf-8")
    print(f"\nГотово: result.csv ({total} записей)")

if __name__ == "__main__":
    main()